def ellipse(cx, cy, rx, ry, toward, n=12):
    return [
        (cx + rx * math.cos(toward + math.tau * k / n), cy + ry * math.sin(toward + math.tau * k / n))
        for k in range(n)
    ]


def loop(ring, links):
    out = []
    for i, p in enumerate(ring):
        out.append(p)
        if i in links:
            out += links[i] + [p]
    return out + [ring[0]]


